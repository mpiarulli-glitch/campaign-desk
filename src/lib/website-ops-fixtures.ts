export function insertWebsiteOpsFixtures(
  actor = "",
  today = "2026-11-09",
  clients: Array<{ id: string; name: string }> = []
): number {
  if (listWebsiteProjects().length) return 0;
  let inserted = 0;
  for (const draft of FIXTURES) {
    const clientId =
      draft.clientId ||
      matchClientId(draft.clientName || draft.name, clients);
    const result = createWebsiteProject({ ...draft, clientId }, actor, today);
    if (result.ok) inserted += 1;
  }
  return inserted;
}
